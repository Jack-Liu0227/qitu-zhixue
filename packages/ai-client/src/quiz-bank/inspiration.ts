import type { QuizBankEntry } from './index.js';

type Item = readonly [concept: string, stem: string, answer: string, wrong: readonly [string, string, string], explanation: string];
function bank(prefix: string, items: readonly Item[]): QuizBankEntry[] {
  const counts = new Map<string, number>();
  return items.map(([concept, stem, answer, wrong, explanation], index) => {
    const number = (counts.get(concept) ?? 0) + 1;
    counts.set(concept, number);
    const choices = [answer, ...wrong];
    const offset = index % choices.length;
    const options = [...choices.slice(offset), ...choices.slice(0, offset)].map((text, i) => ({ key: String.fromCharCode(65 + i), text }));
    return { questionId: `${prefix}.${concept}.q${number}`, conceptId: `${prefix}.${concept}`, stem, type: 'single', options,
      expectedKeys: [options.find(option => option.text === answer)!.key], explanation,
      rationaleHint: '先指出题目中的对象、条件和证据，再比较每个选项能否由这些信息支持。', difficulty: 'easy' };
  });
}

